"""
Generate RESULTS.md from everything under results/ .

The point: a reader (recruiter, hiring engineer, or you in six months) should be
able to see the whole optimisation progression -- what changed, what it bought,
on what hardware, at which commit -- without running anything, and should be
able to reproduce any single row from the SHA.

    python benchmarks/make_report.py
    python benchmarks/make_report.py --out RESULTS.md

NOTE: keep this file Python-3.9 compatible (no `X | None` annotations).
"""
import argparse
import glob
import json
import os

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(REPO_ROOT, "results")


def load(bench):
    runs = []
    for p in sorted(glob.glob(os.path.join(RESULTS, bench, "*.json"))):
        try:
            with open(p) as f:
                d = json.load(f)
            d["_path"] = os.path.relpath(p, REPO_ROOT).replace("\\", "/")
            runs.append(d)
        except (ValueError, OSError):
            continue
    runs.sort(key=lambda r: r.get("provenance", {}).get("utc", ""))
    return runs


def env_line(runs):
    for r in reversed(runs):
        p = r.get("provenance", {})
        if p.get("gpu"):
            return ("Measured on **{gpu}** ({sm}, {hbm} GB HBM) - torch {torch} / "
                    "CUDA {cuda}, Python {py}.".format(
                        gpu=p["gpu"], sm=p.get("sm", "?"),
                        hbm=p.get("hbm_gb", "?"), torch=p.get("torch", "?"),
                        cuda=p.get("cuda", "?"), py=p.get("python", "?")))
    return ""


def fmt(v, spec="{:.4f}"):
    return spec.format(v) if isinstance(v, (int, float)) else "-"


def kernel_progression(runs, ctx):
    """One row per run at a fixed context: the optimisation story."""
    out = ["", "### Split-KV GQA decode kernel at {} context (batch 1, isolated)"
           .format(ctx), "",
           "| Stage | ours (ms) | SDPA (ms) | ratio | % HBM peak | max err | commit |",
           "|---|---:|---:|---:|---:|---:|---|"]
    seen = False
    for r in runs:
        row = next((x for x in r.get("rows", []) if x.get("ctx") == ctx), None)
        if not row:
            continue
        seen = True
        prov = r.get("provenance", {})
        dirty = " (dirty)" if prov.get("git_dirty") else ""
        out.append("| {} | {} | {} | {}x | {} | {} | `{}`{} |".format(
            r.get("label", "?"),
            fmt(row.get("ours_ms")), fmt(row.get("sdpa_ms")),
            fmt(row.get("ratio"), "{:.2f}"),
            fmt(row.get("ours_pct_hbm"), "{:.1f}%"),
            fmt(row.get("max_err"), "{:.5f}"),
            prov.get("git_sha", "?"), dirty))
    return out if seen else []


def serving_table(runs):
    if not runs:
        return []
    latest = runs[-1]
    cfg = latest.get("extra", {})
    out = ["", "## Serving regime - where the KV cache actually hurts", ""]

    cap = cfg.get("capacity", {})
    if cap:
        out += ["Concurrent sequences that fit on one {} GB GPU "
                "({} GB weights, {} GB reserved):".format(
                    cfg.get("hbm_gb", "?"), cfg.get("weight_gb", "?"),
                    cfg.get("reserve_gb", "?")), "",
                "| context | KV per sequence | max concurrent (fp16) | max concurrent (fp8) |",
                "|---:|---:|---:|---:|"]
        for ctx in sorted(cap, key=lambda x: int(x)):
            c = cap[ctx]
            out.append("| {} | {:.2f} GB | {} | {} |".format(
                ctx, c["kv_gb_per_seq"], c["max_seqs_fp16"], c["max_seqs_fp8"]))

    out += ["", "Decode attention measured per layer for the whole batch "
            "(`step_ms`/`tok/s` are modelled: attention x layers + weight read "
            "at peak bandwidth, so they are an upper bound):", "",
            "| batch | ctx | ours (ms) | SDPA (ms) | GB/layer | % HBM | step ms* | tok/s* |",
            "|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for row in latest.get("rows", []):
        out.append("| {} | {} | {} | {} | {} | {} | {} | {} |".format(
            row.get("batch"), row.get("ctx"),
            fmt(row.get("ours_ms")), fmt(row.get("sdpa_ms")),
            fmt(row.get("layer_gb"), "{:.2f}"),
            fmt(row.get("ours_pct_hbm"), "{:.1f}%"),
            fmt(row.get("ours_step_ms_proj"), "{:.1f}"),
            fmt(row.get("ours_tok_s_proj"), "{:.0f}")))
    out.append("")
    out.append("Source: `{}`".format(latest["_path"]))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO_ROOT, "RESULTS.md"))
    args = ap.parse_args()

    kernel = load("kernel_vs_sdpa")
    serving = load("serving_regime")

    doc = ["# Measured results", "",
           "Generated by `benchmarks/make_report.py` from the JSON files under "
           "`results/`. Every row is pinned to the commit that produced it; "
           "nothing here is hand-entered.", ""]
    env = env_line(kernel + serving)
    if env:
        doc += [env, ""]

    if kernel:
        doc += ["## Kernel optimisation progression", "",
                "Isolated decode-attention kernel vs PyTorch SDPA "
                "(FlashAttention family) on Llama-3.1-8B attention shapes "
                "(32 Q / 8 KV heads, head_dim 128). `ratio` < 1.0 means our "
                "kernel is faster. SDPA sits near the memory roofline for exact "
                "attention, so the honest target for the dense kernel is "
                "parity, not victory -- the wins come from moving fewer bytes "
                "(FP8 KV, paged sparsity)."]
        for ctx in (4096, 16384, 64000):
            doc += kernel_progression(kernel, ctx)
        doc += ["", "Raw runs: " + ", ".join("`{}`".format(r["_path"])
                                             for r in kernel[-6:])]
    else:
        doc += ["_No kernel benchmark results recorded yet._"]

    doc += serving_table(serving)

    doc += ["", "---", "",
            "Reproduce any row:", "", "```bash",
            "git checkout <commit>", "source cluster/env.sh",
            '"$PYTHON_BIN" setup.py build_ext --inplace',
            '"$PYTHON_BIN" benchmarks/profile_kernel_vs_sdpa.py --label <stage>',
            '"$PYTHON_BIN" benchmarks/bench_serving_regime.py --label <stage>',
            "```", ""]

    with open(args.out, "w") as f:
        f.write("\n".join(doc))
    try:
        shown = os.path.relpath(args.out, REPO_ROOT)
    except ValueError:                     # different drive on Windows
        shown = args.out
    print("wrote {} ({} kernel runs, {} serving runs)".format(
        shown, len(kernel), len(serving)))


if __name__ == "__main__":
    main()
